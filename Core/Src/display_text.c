static const uint8_t *DisplayText_FindGlyph(char character)
{
  size_t index;

  for (index = 0U; index < (sizeof(glyphs) / sizeof(glyphs[0])); ++index)
  {
    if (glyphs[index].character == character)
    {
      return glyphs[index].rows;
    }
  }

  if ((character >= 'a') && (character <= 'z'))
  {
    character = (char)(character - ('a' - 'A'));
    for (index = 0U; index < (sizeof(glyphs) / sizeof(glyphs[0])); ++index)
    {
      if (glyphs[index].character == character)
      {
        return glyphs[index].rows;
      }
    }
  }

  for (index = 0U; index < (sizeof(glyphs) / sizeof(glyphs[0])); ++index)
  {
    if (glyphs[index].character == '?')
    {
      return glyphs[index].rows;
    }
  }

  return glyphs[0].rows;
}

uint16_t DisplayText_GetWidth(const char *text, uint8_t scale)
{
  uint16_t width = 0U;

  if ((text == NULL) || (scale == 0U))
  {
    return 0U;
  }

  while (*text != '\0')
  {
    width = (uint16_t)(width + ((uint16_t)scale * 6U));
    ++text;
  }

  return (width == 0U) ? 0U : (uint16_t)(width - scale);
}

void DisplayText_DrawString(uint16_t x, uint16_t y, const char *text,
                            uint8_t scale, uint16_t foreground,
                            uint16_t background)
{
  uint8_t row;
  uint8_t column;
  const uint8_t *glyph;

  if ((text == NULL) || (scale == 0U))
  {
    return;
  }

  while (*text != '\0')
  {
    glyph = DisplayText_FindGlyph(*text);
    ILI9341_FillRect(x, y, (uint16_t)(6U * scale),
                     (uint16_t)(7U * scale), background);

    for (row = 0U; row < 7U; ++row)
    {
      for (column = 0U; column < 5U; ++column)
      {
        if ((glyph[row] & (uint8_t)(0x10U >> column)) != 0U)
        {
          ILI9341_FillRect((uint16_t)(x + ((uint16_t)column * scale)),
                           (uint16_t)(y + ((uint16_t)row * scale)),
                           scale, scale, foreground);
        }
      }
    }

    x = (uint16_t)(x + ((uint16_t)scale * 6U));
    ++text;
  }
}
